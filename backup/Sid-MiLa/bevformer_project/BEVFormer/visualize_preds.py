import pickle
import numpy as np

# 1. Load the predictions
pred_file = 'custom_car_predictions.pkl'
try:
    with open(pred_file, 'rb') as f:
        preds = pickle.load(f)
    print(f"✅ Successfully loaded {len(preds)} frames of predictions!")

    # 2. Extract the very first frame's data
    first_frame = preds[0] if isinstance(preds, list) else list(preds.values())[0]
    
    if 'pts_bbox' in first_frame:
        boxes = first_frame['pts_bbox']['boxes_3d']
        scores = first_frame['pts_bbox']['scores_3d']
        labels = first_frame['pts_bbox']['labels_3d']
        
        # 3. Filter for high-confidence detections
        threshold = 0.3
        valid_indices = scores > threshold
        high_conf_boxes = boxes[valid_indices]
        high_conf_scores = scores[valid_indices]
        
        print(f"🚗 Found {len(high_conf_boxes)} objects with >30% confidence in Frame 1!")
        print("Top 3 Scores:", high_conf_scores[:3] if len(high_conf_scores) > 0 else "None")
        
        # Next step will be passing these box coordinates into cv2 (OpenCV) to draw on the image!
    else:
        print("No 3D boxes found in this frame.")
        
except FileNotFoundError:
    print(f"⏳ Waiting for {pred_file} to be generated by the supercomputer...")
